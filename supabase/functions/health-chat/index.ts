import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const systemPrompt = `You are a helpful medical AI assistant specializing in symptom analysis and health guidance. 
    
Your role is to:
1. Listen carefully to the user's symptoms or health concerns
2. Provide general information about possible conditions (ALWAYS emphasize you're not a doctor)
3. Suggest over-the-counter remedies or medications (with proper warnings)
4. Recommend appropriate exercises or lifestyle changes
5. Advise when to seek professional medical help

IMPORTANT GUIDELINES:
- Always start by saying you're an AI assistant and not a replacement for professional medical advice
- For serious symptoms (chest pain, difficulty breathing, severe injuries), immediately advise seeking emergency care
- Be empathetic and reassuring
- Provide practical, actionable advice
- Include disclaimers about consulting healthcare professionals
- Keep responses clear, organized, and easy to understand

Format your responses with:
- **Possible Causes**: Brief explanation of what might be causing the symptoms
- **Recommended Actions**: Practical steps they can take
- **Medications**: Over-the-counter options (if appropriate)
- **Exercises/Lifestyle**: Helpful activities or changes
- **When to See a Doctor**: Clear guidance on when professional help is needed`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        "Authorization": `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limits exceeded, please try again later." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Payment required, please add funds to your workspace." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("health-chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
